const { chromium, devices } = require('playwright-core');
const OUT = process.env.OUT || require('path').join(__dirname, 'out');
const BASE = process.env.BASE || 'http://localhost:8787/';
const results = [];
const check = (name, ok, extra = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`);

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['iPhone 13'], colorScheme: 'dark' });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const wait = ms => page.waitForTimeout(ms);
  const cdp = await ctx.newCDPSession(page);
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] });
  const swipe = async (x1, y1, x2, y2, steps = 12) => {
    await touch('touchStart', x1, y1);
    for (let i = 1; i <= steps; i++) { await touch('touchMove', x1 + (x2 - x1) * i / steps, y1 + (y2 - y1) * i / steps); await wait(16); }
    await touch('touchEnd');
    await wait(400);
  };
  const box = sel => page.locator(sel).first().boundingBox();
  const activeTab = () => page.$eval('.tab.active', t => t.dataset.id);
  const titles = () => page.$$eval('.rtt', r => r.map(x => x.textContent));
  const badge = () => page.$eval('#netBadge', b => b.hidden ? '' : b.textContent);
  const calls = () => page.evaluate(() => window.__calls);
  const closeSheet = () => page.tap('#sheetWrap', { position: { x: 30, y: 30 } });

  await page.goto(BASE);
  await page.waitForSelector('.row');

  await page.tap('#fab');
  await wait(300);
  const epicChips = () => page.$eval('#sheet .chip-line', l => [...l.querySelectorAll('.chip')].map(c => c.textContent));
  const epicActive = () => page.$eval('#sheet .chip-line', l => l.querySelector('.chip.active')?.textContent);
  let chips = await epicChips();
  let active = await epicActive();
  check('smart epics: most recently filled epic first and preselected', chips[0] === 'Проект Бета' && active === 'Проект Бета', chips.join(' | '));
  check('smart epics: next candidates by recency', chips[1] === 'Проект Альфа' && chips[2] === 'Дом', chips.join(' | '));
  await page.tap('#sheet .chip-line .chip:text-is("Дом")');
  await page.keyboard.type('Задача в дом');
  await page.tap('#sheet .add-btn');
  await wait(900);
  await closeSheet();
  await wait(300);
  await page.tap('#fab');
  await wait(300);
  chips = await epicChips();
  active = await epicActive();
  check('smart epics: just-used epic jumps to front', chips[0] === 'Дом' && active === 'Дом', chips.join(' | '));
  await closeSheet();
  await wait(300);

  await page.evaluate(() => localStorage.setItem('mock.offline', '1'));
  let b = await box('.row:has-text("Собрать отчёт")');
  await swipe(b.x + b.width - 30, b.y + b.height / 2, b.x + 40, b.y + b.height / 2);
  await wait(300);
  check('offline: swipe to Done applied locally', !(await titles()).includes('Собрать отчёт'));
  await page.tap('#fab');
  await wait(300);
  await page.keyboard.type('Офлайн задача');
  await page.tap('#sheet .add-btn');
  await wait(300);
  await closeSheet();
  await wait(300);
  check('offline: created task shown as pending', await page.$$eval('.row.pending', r => r.some(x => x.textContent.includes('Офлайн задача'))));
  check('offline: badge shows queue', /Нет сети · 2/.test(await badge()), await badge());
  check('offline: queue persisted', await page.evaluate(() => JSON.parse(localStorage.getItem('pb.queue')).length === 2));
  await page.screenshot({ path: `${OUT}/o1-offline.png` });

  await page.reload();
  await page.waitForSelector('.row');
  await wait(500);
  const afterReload = await titles();
  check('offline reload: changes survive', afterReload.includes('Офлайн задача') && !afterReload.includes('Собрать отчёт'), afterReload.slice(0, 4).join(' | '));
  check('offline reload: badge still shows queue', /Нет сети · 2/.test(await badge()), await badge());

  await page.evaluate(() => { localStorage.removeItem('mock.offline'); window.dispatchEvent(new Event('online')); });
  await wait(3000);
  const c = await calls();
  check('online: queued create sent', c.some(x => x.q.includes('createIssue(') && x.variables.t === 'Офлайн задача'));
  check('online: queued status sent', c.some(x => x.q.includes('updateProjectV2ItemFieldValue') && x.variables.o === 'o5'));
  check('online: queue empty, badge hidden', (await page.evaluate(() => localStorage.getItem('pb.queue'))) === '[]' && (await badge()) === '', await badge());
  check('online: nothing pending', (await page.$$('.row.pending')).length === 0);

  await page.evaluate(() => localStorage.setItem('mock.badToken', 'bearer mock-token'));
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.locator('.row:has-text("Записаться к стоматологу")').scrollIntoViewIfNeeded();
  b = await box('.row:has-text("Записаться к стоматологу")');
  await swipe(b.x + b.width - 30, b.y + b.height / 2, b.x + 40, b.y + b.height / 2);
  await wait(800);
  check('expired token: badge asks for token', /Токен/.test(await badge()), await badge());
  await page.tap('#netBadge');
  await wait(300);
  check('expired token: reauth sheet opens', !!(await page.$('#sheet h2:text-is("Новый токен")')));
  await page.fill('#sheet input[type=password]', 'new-token');
  await page.tap('#sheet button:has-text("Сохранить")');
  await wait(1500);
  const sent = (await calls()).filter(x => x.auth === 'bearer new-token' && x.q.includes('closeIssue'));
  check('expired token: queue replayed with new token', sent.length > 0);
  check('expired token: badge cleared', (await badge()) === '', await badge());

  await page.tap('#searchBtn');
  await wait(300);
  await page.keyboard.type('счетчик');
  await wait(200);
  let found = await page.$$eval('#sheet .search-row .sr-title', r => r.map(x => x.textContent));
  check('search: ё/е insensitive', found.includes('Проверить показания счётчиков'), found.join(' | '));
  check('search: highlight', (await page.$$('#sheet .search-row mark')).length > 0);
  await page.fill('#sheet .search-input', 'фильтры');
  await wait(200);
  check('search: finds Done tasks', await page.$$eval('#sheet .search-row.done', r => r.some(x => x.textContent.includes('Купить фильтры'))));
  await page.fill('#sheet .search-input', 'детали');
  await wait(200);
  found = await page.$$eval('#sheet .search-row .sr-title', r => r.map(x => x.textContent));
  check('search: matches description', found.includes('Оплатить налоги'), found.join(' | '));
  await page.fill('#sheet .search-input', 'бета презентац');
  await wait(200);
  found = await page.$$eval('#sheet .search-row .sr-title', r => r.map(x => x.textContent));
  check('search: all words, epic title counts', found.length === 1 && found[0] === 'Подготовить презентацию', found.join(' | '));
  await page.screenshot({ path: `${OUT}/o2-search.png` });
  await page.tap('#sheet .search-row');
  await wait(400);
  check('search: tap opens task', (await page.inputValue('#sheet textarea.t-title')) === 'Подготовить презентацию');
  await page.evaluate(() => closeSheet());
  await wait(300);

  await page.tap('.tab[data-id="o2"]');
  await wait(300);
  const W = page.viewportSize().width;
  b = await box('.row');
  await swipe(W - 6, b.y + b.height / 2, W - 200, b.y + b.height / 2);
  check('tab swipe from right edge → next tab', (await activeTab()) === 'o3', await activeTab());
  check('edge swipe did not open a sheet', !(await page.$('#sheetWrap.open')));
  const head = await box('.group-head, .empty');
  await swipe(60, head.y + head.height / 2, 300, head.y + head.height / 2);
  check('swipe right on header/empty → previous tab', (await activeTab()) === 'o2', await activeTab());
  const doneCount = await page.$eval('.tab[data-id="o5"] .n', e => +e.textContent);
  await page.locator('.row:has-text("Оплатить налоги")').scrollIntoViewIfNeeded();
  b = await box('.row:has-text("Оплатить налоги")');
  await swipe(b.x + b.width - 40, b.y + b.height / 2, b.x + 60, b.y + b.height / 2);
  check('row swipe still marks done (no tab switch)', (await activeTab()) === 'o2' && (await page.$eval('.tab[data-id="o5"] .n', e => +e.textContent)) === doneCount + 1);
  await page.locator('.tab').first().tap();
  await wait(300);
  const firstTab = await activeTab();
  await swipe(60, 400, 300, 400);
  check('no tab before first: stays', (await activeTab()) === firstTab, await activeTab());

  await page.evaluate(() => { window.__scopes = 'gist, project, repo, workflow'; });
  await page.evaluate(() => load());
  await wait(1200);
  await page.tap('#settingsBtn');
  await wait(300);
  const warn = await page.textContent('#sheet .warn').catch(() => '');
  check('settings warns about extra token scopes', /gist, workflow/.test(warn), warn);

  check('no page errors', errors.length === 0, errors.join('; '));
  console.log(results.join('\n'));
  await browser.close();
  process.exit(results.some(r => r.startsWith('FAIL')) ? 1 : 0);
})().catch(e => { console.log(results.join('\n')); console.error(e); process.exit(1); });
