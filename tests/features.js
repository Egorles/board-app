const { chromium, devices } = require('playwright-core');
const OUT = process.env.OUT || require('path').join(__dirname, 'out');
const BASE = process.env.BASE || BASE;
const results = [];
const check = (name, ok, extra = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`);

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['iPhone 13'], colorScheme: 'dark' });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const wait = ms => page.waitForTimeout(ms);
  const tabNames = () => page.$$eval('.tab', ts => ts.map(t => t.childNodes[1].textContent + ':' + t.querySelector('.n').textContent));
  const groups = () => page.$$eval('.group', gs => gs.map(g => [g.querySelector('.gt')?.textContent, [...g.querySelectorAll('.rtt')].map(r => r.textContent)]));
  const calls = () => page.evaluate(() => window.__calls);
  const closeByBackdrop = () => page.tap('#sheetWrap', { position: { x: 30, y: 30 } });

  await page.goto(BASE);
  await page.waitForSelector('.row');

  let tabs = await tabNames();
  check('no-status tab shown first', tabs[0] === 'Без статуса:1', tabs.join(' '));
  await page.tap('.tab.no-status');
  await wait(200);
  await page.tap('.row:has-text("Задача из удалённого статуса")');
  await wait(300);
  await page.tap('#sheet .chip:has-text("ToDo")');
  await wait(500);
  await page.tap('#sheet button:has-text("Закрыть")');
  await wait(400);
  tabs = await tabNames();
  check('no-status tab disappears after assigning status', !tabs.some(t => t.startsWith('Без статуса')), tabs.join(' '));

  await page.tap('.tab:has-text("ToDo")');
  await wait(200);
  await page.tap('#fab');
  await wait(300);
  await page.keyboard.type('Задача с описанием');
  await page.keyboard.press('Enter');
  check('Enter in title moves focus to description', await page.evaluate(() => document.activeElement?.classList.contains('new-body')));
  await page.keyboard.type('Первая строка');
  await page.keyboard.press('Enter');
  await page.keyboard.type('Вторая строка');
  check('Enter in description makes new line', (await page.inputValue('.new-body')) === 'Первая строка\nВторая строка');
  await page.tap('#sheet .chip:has-text("Проект Бета")');
  await page.tap('#sheet label.toggle:has-text("Закрыть после")');
  await page.tap('#sheet button:has-text("Добавить")');
  await wait(150);
  check('close-after-add closes sheet', !(await page.$('#sheetWrap.open')));
  const pendingInfo = await page.evaluate(() => {
    const row = [...document.querySelectorAll('.row.pending')][0];
    if (!row) return null;
    const wrap = row.parentElement;
    return { spinner: !!row.querySelector('.spinner'), acts: [...wrap.querySelectorAll('.swipe-act')].map(a => getComputedStyle(a).visibility) };
  });
  check('pending row shows spinner, swipe backgrounds hidden', pendingInfo && pendingInfo.spinner && pendingInfo.acts.every(v => v === 'hidden'), JSON.stringify(pendingInfo));
  await wait(1200);
  const createCall = (await calls()).find(c => c.q.includes('createIssue') && c.variables.t === 'Задача с описанием');
  check('description sent to GitHub', createCall?.variables.b === 'Первая строка\nВторая строка', JSON.stringify(createCall?.variables));
  check('one request saved: no addProjectV2ItemById', !(await calls()).some(c => c.q.includes('addProjectV2ItemById')));
  check('close-after-add remembered', await page.evaluate(() => localStorage.getItem('pb.closeAfterAdd') === 'true'));
  const g1 = await groups();
  check('created task in Проект Бета with notes mark', g1.some(([g, r]) => g === 'Проект Бета' && r.includes('Задача с описанием')));

  await page.tap('#fab');
  await wait(300);
  await page.tap('#sheet label.toggle:has-text("Закрыть после")');
  await page.keyboard.type('Гонка с обновлением');
  await page.evaluate(() => { load(); });
  await page.tap('#sheet button:has-text("Добавить")');
  check('unchecked close-after-add keeps sheet', !!(await page.$('#sheetWrap.open')));
  await wait(2000);
  await closeByBackdrop();
  await wait(300);
  const raceCount = await page.$$eval('.rtt', r => r.filter(x => x.textContent === 'Гонка с обновлением').length);
  check('task created during refresh shown exactly once', raceCount === 1, `count=${raceCount}`);
  await page.evaluate(() => { load(); });
  await wait(1200);
  const raceAfterReload = await page.$$eval('.rtt', r => r.filter(x => x.textContent === 'Гонка с обновлением').length);
  check('mock reload (server without task) drops it — expected for mock', raceAfterReload === 0, `count=${raceAfterReload}`);

  await page.tap('#settingsBtn');
  await wait(300);
  await page.tap('#sheet .list-row:has-text("Проекты")');
  await wait(300);
  await page.fill('#sheet .inline-add input', 'Тестовый проект');
  await page.tap('#sheet .inline-add button');
  await wait(900);
  const epicList = await page.$$eval('#sheet .list-row .lr-title', r => r.map(x => x.textContent));
  check('new epic created and listed', epicList.includes('Тестовый проект'), epicList.join(' | '));
  check('project created as new field option', (await calls()).some(c => c.q.includes('updateProjectV2Field(') && c.variables.f === 'PF' && c.variables.o.some(o => !o.id && o.name === 'Тестовый проект') && c.variables.o.filter(o => o.id).length === 3));
  await page.screenshot({ path: `${OUT}/f1-epics.png` });

  await page.tap('#sheet .list-row:has-text("Дом")');
  await wait(300);
  check('bulk move starts with nothing selected', (await page.textContent('#sheet .btn.primary.wide')).includes('Выбери задачи'));
  await page.tap('#sheet label.pick-row:has-text("Собрать отчёт")');
  await page.tap('#sheet label.pick-row:has-text("Почистить телефон")');
  const btnText = await page.textContent('#sheet .btn.primary.wide');
  check('selection counter', btnText.includes('2'), btnText);
  await page.tap('#sheet .chip:has-text("Тестовый проект")');
  await page.screenshot({ path: `${OUT}/f2-epic.png` });
  await page.tap('#sheet .btn.primary.wide');
  await wait(900);
  const g2 = await groups();
  const moved = g2.find(([g]) => g === 'Тестовый проект');
  check('bulk move puts 2 tasks into new epic', moved && moved[1].length === 2, JSON.stringify(moved));
  const bulk = (await calls()).filter(c => c.q.includes('m0: updateProjectV2ItemFieldValue')).at(-1);
  check('bulk move is one aliased request', bulk && bulk.q.includes('m1: updateProjectV2ItemFieldValue') && bulk.q.includes('"PF"'), bulk?.q);

  await page.tap('.group:has(.gt:text-is("Тестовый проект")) .gh-more');
  await wait(300);
  await page.fill('#sheet textarea.t-title', 'Проект переименован');
  await closeByBackdrop();
  await wait(700);
  const g3 = await groups();
  check('rename epic updates group title', g3.some(([g]) => g === 'Проект переименован'), g3.map(g => g[0]).join(' | '));
  check('rename sent as field option update', (await calls()).some(c => c.q.includes('updateProjectV2Field(') && c.variables.o.some(o => o.id && o.name === 'Проект переименован')));

  await page.tap('#settingsBtn');
  await wait(300);
  await page.tap('#sheet .list-row:has-text("Статусы")');
  await wait(300);
  const names = await page.$$('#sheet .st-name');
  await names[3].fill('Пауза');
  await page.tap('#sheet .st-row:nth-child(1) .st-btn.danger');
  await page.tap('#sheet button:has-text("Добавить статус")');
  const all = await page.$$('#sheet .st-name');
  await all.at(-1).fill('Ждёт ответа');
  await page.tap('#sheet .st-row:nth-child(1) .st-btn.danger');
  await page.screenshot({ path: `${OUT}/f3-statuses.png` });
  await page.tap('#sheet button:has-text("Сохранить")');
  await wait(800);
  tabs = await tabNames();
  check('statuses saved: renamed/added/removed', tabs.some(t => t.startsWith('Пауза')) && tabs.some(t => t.startsWith('Ждёт ответа')) && !tabs.some(t => t.startsWith('Notes:')) && !tabs.some(t => t.startsWith('Backlog:')), tabs.join(' '));
  check('deleted status with task → Без статуса tab', tabs[0] === 'Без статуса:2', tabs[0] + ' (1 из удалённого Backlog + 1 мок вернул без статуса)');
  const st = (await calls()).filter(c => c.q.includes('updateProjectV2Field(')).at(-1);
  check('existing options keep ids', st && st.variables.o.filter(o => o.id).map(o => o.id).join(',') === 'o2,o3,o4,o5' && st.variables.o.some(o => !o.id && o.name === 'Ждёт ответа'), JSON.stringify(st?.variables.o));

  check('no page errors', errors.length === 0, errors.join('; '));
  console.log(results.join('\n'));
  await browser.close();
  process.exit(results.some(r => r.startsWith('FAIL')) ? 1 : 0);
})().catch(e => { console.log(results.join('\n')); console.error(e); process.exit(1); });
